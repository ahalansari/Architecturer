// Compile researched market rates (data/market-rates/<country>/*.json) into src/cost/market_<country>.ts.
//   node scripts/build-market-rates.mjs [kw]
// Each JSON file is an array of { key, value, low, high, unit, basis, source, url, quote, accessed, confidence, note }.
// Entries with value null are kept out (the estimate falls back to its indicative rate and says so).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const country = process.argv[2] ?? "kw";
const dir = join("data", "market-rates", country);
const rows = [];
const seen = new Map();
for (const f of readdirSync(dir).filter((x) => x.endsWith(".json")).sort()) {
  for (const r of JSON.parse(readFileSync(join(dir, f), "utf8"))) {
    if (typeof r.key !== "string") throw new Error(`${f}: entry without key`);
    if (r.value === null || r.value === undefined) continue;
    if (typeof r.value !== "number" || !isFinite(r.value) || r.value < 0) throw new Error(`${f}: ${r.key}: bad value ${r.value}`);
    if (!r.url || !/^https?:\/\//.test(r.url)) throw new Error(`${f}: ${r.key}: missing source URL`);
    if (seen.has(r.key)) throw new Error(`${f}: ${r.key} also in ${seen.get(r.key)}`);
    seen.set(r.key, f);
    rows.push({ key: r.key, value: r.value, low: r.low ?? null, high: r.high ?? null, unit: r.unit, basis: r.basis, source: r.source, url: r.url, quote: r.quote ?? "", accessed: r.accessed, confidence: r.confidence, note: r.note ?? "" });
  }
}
rows.sort((a, b) => a.key.localeCompare(b.key));
const ts = `// GENERATED by scripts/build-market-rates.mjs from data/market-rates/${country}/*.json — do not edit by hand.
import type { MarketRate } from "./market.js";

export const MARKET_${country.toUpperCase()}: MarketRate[] = ${JSON.stringify(rows, null, 1)};
`;
writeFileSync(join("src", "cost", `market_${country}.ts`), ts);
console.log(`wrote src/cost/market_${country}.ts: ${rows.length} rates`);
